"""# Phase 3: Dataset Preparation and Exploration

In this phase, we:
1. Download the sample standard dataset (`coco8`).
2. Explore its file structure.
3. Read a raw text annotation file to inspect normalized coordinates.
4. Write a script to visualize bounding boxes overlaid on a sample image.
"""

import os
from ultralytics.utils.downloads import download
from zipfile import ZipFile

# 1. Download the mini coco8 dataset
# Ultralytics provides convenient links for sample datasets
url = 'https://ultralytics.com/assets/coco8.zip'
download(url, dir='.')

# Unzip the downloaded dataset
with ZipFile('coco8.zip', 'r') as zip_ref:
    zip_ref.extractall('.')

print("Dataset downloaded and unzipped successfully!")

# 2. Explore the structure of the dataset
print("\n--- Dataset Structure ---")
for root, dirs, files in os.walk('coco8'):
    level = root.replace('coco8', '').count(os.sep)
    indent = ' ' * 4 * (level)
    print(f"{indent}{os.path.basename(root)}/")
    subindent = ' ' * 4 * (level + 1)
    for f in files[:3]:  # print up to 3 files per directory to keep it clean
        print(f"{subindent}{f}")

import cv2
import matplotlib.pyplot as plt

# 3. Read and print a raw YOLO annotation label
sample_label_path = 'coco8/labels/train/000000000009.txt'
sample_image_path = 'coco8/images/train/000000000009.jpg'

print("Raw YOLO annotation text (class_id, x_center, y_center, width, height):")
with open(sample_label_path, 'r') as f:
    annotations = f.read().strip().split('\n')
    for ann in annotations:
        print(ann)

# 4. Map the normalized bounding box coordinates and visualize
img = cv2.imread(sample_image_path)
img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
h, w, _ = img.shape

for ann in annotations:
    class_id, x_c, y_c, bbox_w, bbox_h = map(float, ann.split())

    # Convert normalized coordinates back to pixel coordinates
    x1 = int((x_c - bbox_w / 2) * w)
    y1 = int((y_c - bbox_h / 2) * h)
    x2 = int((x_c + bbox_w / 2) * w)
    y2 = int((y_c + bbox_h / 2) * h)

    # Draw the bounding boxes on the image using OpenCV
    cv2.rectangle(img_rgb, (x1, y1), (x2, y2), (0, 255, 0), 3)
    cv2.putText(img_rgb, f"Class {int(class_id)}", (x1, y1 - 10),
                cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 0, 0), 2)

plt.figure(figsize=(10, 8))
plt.imshow(img_rgb)
plt.axis('off')
plt.title("Visualizing Bounding Box on Sample Image")
plt.show()

